import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(p,"utf8");
const home=read("index.html");
const module=read("home-nearme-v2.js");
const foundation=read("home-foundation-v2.js");
const support=JSON.parse(read("data/home-support.json"));
const index=JSON.parse(read("data/views/location-index.json"));
const utilities=JSON.parse(read("data/entities/utilities.json"));
const core=["PHARMACY","ATM","FUEL","TOILET","MINIMART","CHARGING"];
const additional=["PARKING","LAUNDRY"];
for(const id of [...core,...additional]){
 assert.ok(support.near_me.categories.some(x=>x.id===id),"Missing Near Me category "+id);
 assert.ok(module.includes('"'+id+'"'),"Homepage quick finder missing "+id);
}
assert.deepEqual(support.near_me.categories.find(x=>x.id==="CHARGING")?.mode,"directory_search");
assert.ok(index.documents.some(x=>x.entity_type==="utility"&&x.tags.includes("PHARMACY")));
assert.ok(index.documents.some(x=>x.entity_type==="utility"&&x.tags.includes("ATM")));
assert.ok(index.documents.some(x=>x.entity_type==="utility"&&x.tags.includes("MINIMART")));
assert.equal(utilities.entities.find(x=>x.id==="utility_115")?.phone,"115");
assert.match(home,/id="nearCategories"/);
assert.match(home,/id="nearQuickMore"[^>]*hidden/,"Extra categories initially collapsed");
assert.match(home,/class="near-quick-results" hidden/,"No empty desktop results before user intent");
assert.match(home,/id="nearQuickSearch"/);
assert.match(home,/id="nearQuickStatus"/);
assert.match(home,/id="nearQuickResultsTitle"/,"Quick finder needs a context-aware result heading");
assert.match(home,/id="nearAreaChange"/,"Homepage shares the header region selector");
assert.match(home,/id="nearAreaLabel"/);
assert.doesNotMatch(home,/id="nearManualAreas"/,"Avoid duplicate area pills on homepage");
assert.match(home,/id="nearOtherToggle"/);
assert.ok(module.includes("syncCompactState()"));
assert.ok(module.includes("near-has-selection"));
assert.ok(module.includes("return Boolean(category||gps||query.trim())"),"Shared region alone must not trigger results");
assert.doesNotMatch(module,/nearManualAreas/,"Homepage should not duplicate the area controls");
assert.ok(module.includes("near-show-other"));
assert.match(home,/href="tel:115"/);
assert.match(home,/nearme\/\?category=CLINIC_HOSPITAL/);
assert.match(home,/home-nearme-v2.js\?v=[^\"]+/);
assert.ok(module.includes('load("data/views/location-index.json"'),"Homepage must consume the same Near Me location index");
assert.ok(module.includes("window.OpenPQPublicData?.json"),"Homepage Near Me should reuse the shared request cache");
assert.ok(module.includes('getIndex()'),"Canonical index should load only when requested");
assert.ok(module.includes("rows.slice(0,3)"),"The results should show at most 3 cards");
assert.ok(module.includes('new URLSearchParams()'),"Keep selected filters in the handoff");
assert.ok(module.includes('tel:'),"Verified phone numbers should be directly dialable");
assert.ok(module.includes('google.com/maps/dir/'),"Provide one-click directions");
assert.match(module,/const CORE=\["PHARMACY","ATM","FUEL","TOILET","MINIMART","CHARGING"\]/,"Six useful homepage essentials");
assert.match(module,/function itemUrl\(row\)/,"Home results must link to the internal Near Me map");
assert.match(module,/map\.precision!=="exact_entrance"/,"Never promise turn-by-turn directions to approximate pins");
assert.ok(module.includes('["exact_entrance","site_centroid"].includes(map.precision)'),"Use verified entrance and site coordinates only");
assert.ok(module.includes("query.trim()&&category"),"Free-text search clears stale category");
assert.match(read("styles.css"),/#near-me\{scroll-margin-top:122px\}/,"Anchor clears the fixed desktop header");
assert.equal(module.split("getCurrentPosition(").length-1,1,"GPS may only be requested from its click handler");
assert.match(module,/addEventListener\("click",\(\)=>\{\s*const button=\$\("#nearLocationBtn"\)/);
assert.match(foundation,/openpq:home-support-ready/);
assert.doesNotMatch(foundation,/function renderNearResults\(/);
assert.doesNotMatch(home,/<iframe[^>]*near/i);
console.log("Homepage Near Me quick finder contracts PASS");
