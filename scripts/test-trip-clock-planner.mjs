import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {runInNewContext} from "node:vm";
const read=p=>JSON.parse(readFileSync(p,"utf8"));
const host={};runInNewContext(readFileSync("core/trip-clock-planner.js","utf8"),{window:host,Map,Number,String,Array,Math,RegExp,Object});
const planner=host.OpenPQTripClockPlanner;
const support=read("data/home-support.json"),places=read("data/entities/places.json"),activities=read("data/entities/activities.json");
const entities=new Map([...places.entities,...activities.entities].map(e=>[e.id,e]));
const check=(hour,min=0,weather="unknown",weekday=4)=>planner.plan({items:support.trip_clock.items,entities,nowMinute:hour*60+min,sunsetMinute:1079,weekday,sunsetWeather:weather});
const pick=(rows,id)=>{const row=rows.find(r=>r.item.entity_id===id);assert.ok(row,"missing "+id);return row};
assert.equal(planner.durationMin("1,5–2 giờ"),90);
assert.equal(pick(check(12,42),"place_vinpearl_safari").eligible,false);
assert.equal(pick(check(12,42),"place_vinwonders").eligible,false);
assert.equal(pick(check(12,42),"place_dinh_cau").decision.state,"future");
assert.equal(pick(check(12,42),"place_ho_quoc").eligible,true);
assert.equal(pick(check(9,30),"place_vinpearl_safari").eligible,true);
assert.equal(pick(check(9,30),"place_vinwonders").eligible,true);
assert.equal(pick(check(11),"place_vinwonders").eligible,false);
assert.equal(pick(check(16),"place_ho_quoc").eligible,false);
assert.equal(pick(check(14),"activity_once_show").eligible,true);
assert.equal(pick(check(17,40),"activity_once_show").eligible,true);
assert.equal(pick(check(17,41),"activity_once_show").eligible,false);
assert.equal(pick(check(19),"activity_once_show").eligible,false);
assert.match(pick(check(16,10,"bad"),"place_dinh_cau").note,/mưa hoặc dông/);
const hoQuoc=pick(check(12,42),"place_ho_quoc");assert.ok(!hoQuoc.summary.includes(hoQuoc.note));
console.log("CMS trip-clock regression: 15/15 PASS - Safari, VinWonders, ONCE, Dinh Cau, Ho Quoc, travel buffer.");
