import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const source=fs.readFileSync(new URL("../admin/editor-fields.js",import.meta.url),"utf8");
const root={};
vm.runInNewContext(source,{window:root,globalThis:root,Object,Array,String,Number,RegExp});
let moduleId="stories";
const esc=s=>String(s??"").replace(/[&<>"']/g,m=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#039;"}[m]));
const labelize=k=>({title:"Tiêu đề",role:"Vai trò"}[k]||String(k));
const f=root.OPQEditorFields.create({getModuleId:()=>moduleId,labelize,esc});
assert.equal(f.itemTitle({title:"Bài"},0),"Bài");
assert.equal(f.itemTitle({},2),"Mục 3");
assert.equal(f.inputAttrs("phone"),' type="tel" inputmode="tel"');
assert.equal(f.inputAttrs("url"),' type="url" inputmode="url"');
assert.match(f.stringField("image","/a.jpg","stories.0.image"),/Ảnh cover/);
assert.match(f.stringField("intro","a".repeat(100),"stories.0.intro"),/<textarea/);
assert.match(f.primitiveField("enabled",true,"users.0.enabled"),/data-type="boolean"/);
assert.match(f.primitiveField("read_minutes",4,"stories.0.read_minutes"),/type="number"/);
assert.match(f.primitiveField("role","editor","users.0.role"),/>Biên tập viên<\/option>/);
moduleId="venues";
assert.match(f.primitiveField("coordinate_confidence","HIGH","entities.0.coordinate_confidence"),/Độ tin cậy tọa độ/);
assert.match(f.primitiveField("zone_code","south","entities.0.zone_code"),/Nam đảo \/ An Thới/);
assert.match(f.primitiveField("status","ACTIVE","entities.0.status"),/Đang dùng/);
moduleId="visuals";
assert.match(f.stringField("url","https://example.com/a.jpg","places.x.images.0.url"),/media-upload/);
assert.match(f.stringField("url","https://example.com/a.jpg","places.x.images.0.url"),/Mở nguồn ↗/);
moduleId="stories";
const tree=f.renderNode([{title:"Một",body:"Nội dung"}],"stories","Bài viết",0);
assert.match(tree,/data-array-action="duplicate"/);
assert.match(tree,/data-path="stories\.0\.title"/);
assert.match(tree,/1 mục/);
console.log("PASS CMS editor field renderer extraction");
