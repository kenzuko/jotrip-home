import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const root={};
vm.runInNewContext(fs.readFileSync("admin/story-composer.js","utf8"),{window:root});
const composer=root.OPQStoryComposer;
assert.equal(composer.validLayout("full"),"full");
assert.equal(composer.validLayout("<script>"),"wide");
assert.match(composer.layoutControl("body","stories.0.sections.0.layout"),/data-story-layout-pick="body"/);
assert.match(composer.coverControl("top","stories.0.cover_position"),/data-story-cover-pick="top"/);
assert.doesNotMatch(composer.layoutControl("body",'"><img src=x>'),/<img src=x>/);
const sections=[{heading:"Buổi sáng",body:"Đoạn đầu.\n\nĐoạn sau.",image:"",caption:"",layout:"body"}];
const split=composer.splitForImage(sections,0,10);
assert.equal(split.photoIndex,1);
assert.equal(split.continuation,2);
assert.equal(sections.length,3);
assert.equal(sections[0].heading,"Buổi sáng");
assert.equal(sections[0].body,"Đoạn đầu.\n");
assert.equal(sections[1].image,"");
assert.equal(sections[1].layout,"wide");
assert.equal(sections[2].body,"\nĐoạn sau.");
assert.equal(sections[2].heading,"");
const next=composer.insertAfter(sections,2,"text");
assert.equal(next,3);assert.equal(sections.length,4);
assert.equal(composer.insertAfter(sections,200,"image"),-1);
assert.equal(composer.splitForImage(sections,200,0),null);
const noSplit=[{heading:"",body:"abc"}];
const after=composer.splitForImage(noSplit,0,3);
assert.equal(after.photoIndex,1);assert.equal(after.continuation,null);
assert.equal(noSplit.length,2);
assert.equal(noSplit[0].body,"abc");
console.log("PASS: Story Composer inserts photo/text blocks, preserves paragraph order and rejects invalid indices");
