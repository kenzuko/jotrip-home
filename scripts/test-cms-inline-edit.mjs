import assert from "node:assert/strict";
import vm from "node:vm";
import {readFileSync} from "node:fs";
const src=readFileSync("core/cms-inline-edit.js","utf8");
const w={addEventListener(){}},d={readyState:"loading",addEventListener(){}};
vm.runInNewContext(src,{window:w,document:d});
const t=w.OPQInlineEditorTest;
assert.equal(t.roleOK("admin"),true);assert.equal(t.roleOK("editor"),true);
assert.equal(t.roleOK("viewer"),false);assert.equal(t.roleOK("operator"),false);
const story={title:"Tựa",sections:[{heading:"Đoạn đầu",body:"Một câu"}]};
assert.equal(t.goodField(story,"sections.0.body"),true);
assert.equal(t.goodField(story,"sections.2.body"),false);
assert.equal(t.goodField(story,"__proto__"),false);
assert.equal(t.write(story,"sections.0.body","Đã sửa"),true);
assert.equal(t.read(story,"sections.0.body"),"Đã sửa");
assert.equal(t.write(story,"__proto__","x"),false);
assert.match(t.paras("<script>alert(1)</script>"),/&lt;script&gt;/);
assert.doesNotMatch(t.paras("<img src=x onerror=alert(1)>"),/<img/);
const article=readFileSync("stories/article.html","utf8");
const loader=readFileSync("core/cms-editor-loader.js","utf8");
assert.match(article,/cms-editor-loader\.js\?v=1/);
assert.match(article,/cmsEditor="story"/);
assert.match(loader,/cms-draft-client\.js\?v=1/);
assert.match(loader,/cms-inline-edit\.js\?v=2/);
assert.ok(loader.indexOf("cms-draft-client.js")<loader.indexOf("cms-inline-edit.js"),"Draft client must load before inline editor");
assert.match(src,/id="inlineCmsPublish"[^>]*hidden>Xuất bản/);
assert.match(src,/S\.role==="admin"\)\$\("#inlineCmsPublish"\)\.disabled=false/);
assert.doesNotMatch(src,/Lưu thẳng \(Admin\)/);
assert.ok(src.includes('location.hostname!=="cms.openphuquoc.com"'),"Inline editing must stay on the CMS host");
assert.ok(!src.includes('location.hostname==="openphuquoc.com"'),"Public canonical must never become an inline-edit origin");
assert.match(src,/OPQDraftStore/,"Inline editing must use the server draft client");
console.log("PASS CMS inline edit: CMS-only host gate, server draft client, role gate, field whitelist and safe preview");
