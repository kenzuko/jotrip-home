import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const source=readFileSync("functions/_shared/seo-html.js","utf8");
const seo=await import("data:text/javascript;base64,"+Buffer.from(source).toString("base64"));
const story={id:"phan-biet-tieu",title:"Tiêu Phú Quốc & chuyện vườn",dek:"Nội dung mô tả",intro:"Mở bài\n\nĐoạn hai",updated_at:"2026-09-27",sections:[{heading:"Cách làm",body:"Câu chuyện thực địa."}]};
const article=seo.buildStoryMeta(story);
assert.equal(article.canonical,"https://openphuquoc.com/stories/article.html?id=phan-biet-tieu");
assert.equal(article.type,"article");
assert.match(seo.storyBody(story),/<h1 itemprop="headline">Tiêu Phú Quốc &amp; chuyện vườn<\/h1>/);
assert.match(seo.storyBody(story),/Câu chuyện thực địa/);
assert.ok(!seo.storyBody(story).includes("undefined"));
const knowledge={topic_id:"knowledge_001",title:"Cẩm nang biển",route:"/guide/article.html?id=knowledge_001",editorial:{short_summary:"Thông tin đã duyệt",practical:"Thực tế ở đảo",expectation_vs_reality:"Điều lưu ý",before_you_go:["Coi thời tiết"]},media:{images:[{url:"/assets/test.jpg",alt:"Biển"}]},links:[{label:"Nguồn",url:"https://example.com"}]};
const m=seo.buildKnowledgeMeta(knowledge);
assert.equal(m.canonical,"https://openphuquoc.com/guide/article.html?id=knowledge_001");
assert.match(seo.knowledgeBody(knowledge),/Thông tin đã duyệt/);
assert.match(seo.knowledgeBody(knowledge),/Coi thời tiết/);
const unsafe={...story,title:'Bài <script>alert("bad")</script>'};
assert.ok(!seo.storyBody(unsafe).includes("<script>"));
assert.match(seo.storyBody(unsafe),/&lt;script&gt;/);
assert.equal(seo.buildStoryMeta({id:"x"}),null);
assert.equal(seo.buildKnowledgeMeta({topic_id:"x"}),null);
const worker=readFileSync("worker.js","utf8");
assert.match(worker,/rewriteSeoHtml\(assetResponse, meta\)/);
assert.match(worker,/\["draft","pending","review","scheduled"\]/);
for(const path of ["functions/stories/article.html.js","functions/guide/article.html.js"]){
 const c=readFileSync(path,"utf8");
 assert.match(c,/rewriteSeoHtml/);
 assert.ok(c.includes("article.html"));
}
console.log("SEO server-render test PASS: full published body, HTML escaping and canonical URL");
